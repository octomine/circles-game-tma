import type { Metadata } from 'next';
import localFont from 'next/font/local';
import { getLocale, getMessages } from 'next-intl/server';
import type { ReactNode } from 'react';

import '../src/app/styles/globals.css';

import { AppProviders } from './providers';

const nunito = localFont({
  src: [
    {
      path: './fonts/nunito-cyrillic-400-normal.woff2',
      weight: '400',
      style: 'normal',
    },
    {
      path: './fonts/nunito-cyrillic-700-normal.woff2',
      weight: '700',
      style: 'normal',
    },
    {
      path: './fonts/nunito-cyrillic-900-normal.woff2',
      weight: '900',
      style: 'normal',
    },
  ],
  variable: '--font-nunito',
  display: 'swap',
});

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: ReactNode;
}>) {
  const locale = await getLocale();
  const messages = await getMessages();

  return (
    <html lang="en" className={`${nunito.variable} h-full antialiased`}>
      <body className="bg-background text-text flex min-h-full flex-col font-sans">
        <AppProviders messages={messages} locale={locale}>
          {children}
        </AppProviders>
      </body>
    </html>
  );
}
